void gfx_rect(gfx_surface *s,int x,int y,int w,int h,uint16_t color)
{
    int row,col;
    if (!s || !s->pixels || !s->stride || !s->width || !s->height || w<=0 || h<=0) return;
    if (x<0) {w+=x;x=0;}
    if (y<0) {h+=y;y=0;}
    if ((unsigned)x>=s->width || (unsigned)y>=s->height) return;
    if ((unsigned)w>s->width-(unsigned)x) w=(int)(s->width-(unsigned)x);
    if ((unsigned)h>s->height-(unsigned)y) h=(int)(s->height-(unsigned)y);
    if (w<=0 || h<=0) return;
    for (row=0;row<h;row++)
        for (col=0;col<w;col++)
            s->pixels[(size_t)(y+row)*s->stride+(unsigned)x+(unsigned)col]=color;
}
void gfx_clear(gfx_surface *s,uint16_t color)
{
    if (s) gfx_rect(s,0,0,(int)s->width,(int)s->height,color);
}
void gfx_text(gfx_surface *s,int x,int y,const char *str,uint16_t color)
{
    if (!str) return;
    while (*str) {
        unsigned i,j,k;
        const unsigned char *g=glyphs[0];
        for (k=0;chars[k];k++)
            if (chars[k]==*str) {g=glyphs[k];break;}
        for (i=0;i<5;i++) for (j=0;j<7;j++)
            if (g[i]&(1u<<j))
                gfx_rect(s,x+(int)i*2,y+(int)j*2,2,2,color);
        x+=12;str++;
    }
}
